import assert from 'node:assert/strict'

export async function runUiPolishChecks({ check, navigate, evaluate, until, pause, viewport, screenshot, send, origin, takePausedRequests }) {
  const media = (reduced = 'reduce') => send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: reduced }] })
  const ratio = () => evaluate(() => new DOMMatrix(getComputedStyle(document.querySelector('[data-scroll-progress]')).transform).a)
  await media()
  for (const width of [360, 390, 430, 768, 1024, 1440]) {
    await viewport(width)
    await check(`Floating controls stay fixed; 4px progress tracks top/middle/bottom at ${width}px`, async () => {
      await navigate('/terms')
      await evaluate(() => scrollTo({ top: 0, behavior: 'instant' })); await pause(250)
      const initial = await evaluate(() => {
        const whatsapp = document.querySelector('a[aria-label*="on WhatsApp"]'), back = document.querySelector('button[aria-label="Back to top"]'), bar = document.querySelector('[data-scroll-progress]')
        const r = whatsapp.getBoundingClientRect(), style = getComputedStyle(bar)
        return { y: r.y, bottom: r.bottom, arrowTop: back.getBoundingClientRect().top, hidden: getComputedStyle(back).visibility, disabled: back.disabled, tabIndex: back.tabIndex, height: bar.getBoundingClientRect().height, top: bar.getBoundingClientRect().top, color: style.backgroundColor, events: style.pointerEvents, shadow: style.boxShadow, border: style.borderTopWidth }
      })
      assert.equal(initial.height, 4); assert.equal(initial.top, 0); assert.equal(initial.color, 'rgb(217, 182, 91)')
      assert.equal(initial.events, 'none'); assert.equal(initial.shadow, 'none'); assert.equal(initial.border, '0px')
      assert.equal(initial.hidden, 'hidden'); assert.ok(initial.disabled); assert.equal(initial.tabIndex, -1)
      assert.ok(initial.bottom < initial.arrowTop)
      assert.ok(await ratio() < 0.01)
      await evaluate(() => scrollTo({ top: (document.documentElement.scrollHeight - innerHeight) / 2, behavior: 'instant' })); await pause(200)
      assert.ok(Math.abs(await ratio() - 0.5) < 0.02)
      await evaluate(() => scrollTo({ top: document.documentElement.scrollHeight, behavior: 'instant' })); await pause(250)
      const bottom = await evaluate(() => ({ y: document.querySelector('a[aria-label*="on WhatsApp"]').getBoundingClientRect().y, visible: getComputedStyle(document.querySelector('button[aria-label="Back to top"]')).visibility }))
      assert.equal(bottom.y, initial.y); assert.equal(bottom.visible, 'visible'); assert.ok(await ratio() > 0.99)
      await evaluate(() => document.querySelector('button[aria-label="Back to top"]').click())
      await until(() => scrollY === 0); await pause(250)
      assert.equal(await evaluate(() => document.querySelector('a[aria-label*="on WhatsApp"]').getBoundingClientRect().y), initial.y)
      assert.equal(await evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    })
  }
  await viewport(1440)
  await check('Progress resets on route change and follows back/forward restoration', async () => {
    await navigate('/terms')
    await evaluate(() => scrollTo({ top: document.documentElement.scrollHeight, behavior: 'instant' })); await pause(150)
    await evaluate(() => document.querySelector('footer a[href="/about"]').click())
    await until(() => location.pathname === '/about' && scrollY === 0 && !!document.querySelector('main h1'))
    await pause(200); assert.ok(await ratio() < 0.01)
    await evaluate(() => history.back())
    await until(() => location.pathname === '/terms' && scrollY > 0); await pause(250)
    assert.ok(await ratio() > 0.99)
  })
  await check('Custom cursor follows a mouse, enlarges on CTA and yields to inputs/selection', async () => {
    await send('Emulation.setTouchEmulationEnabled', { enabled: false }); await media('no-preference')
    await navigate('/contact')
    const fine = await evaluate(() => matchMedia('(hover: hover) and (pointer: fine)').matches)
    assert.ok(fine, 'Desktop test needs a fine mouse pointer')
    const point = await evaluate(() => { const r = document.querySelector('header .btn-primary').getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
    await send('Input.dispatchMouseEvent', { type: 'mouseMoved', ...point }); await pause(180)
    const cursor = await evaluate(() => { const el = document.querySelector('[data-custom-cursor]'), ring = el.querySelector('.solar-cursor-ring'), m = new DOMMatrix(getComputedStyle(el).transform); return { visible: getComputedStyle(el).visibility, interactive: el.dataset.interactive, primary: el.dataset.primary, width: ring.getBoundingClientRect().width, events: getComputedStyle(el).pointerEvents, x: m.e, y: m.f } })
    assert.equal(cursor.visible, 'visible'); assert.equal(cursor.interactive, 'true'); assert.equal(cursor.primary, 'true'); assert.equal(cursor.width, 34); assert.equal(cursor.events, 'none')
    assert.ok(Math.abs(cursor.x - point.x) < 1 && Math.abs(cursor.y - point.y) < 1)
    await evaluate(() => document.querySelector('form input').scrollIntoView({ block: 'center' }))
    const field = await evaluate(() => { const r = document.querySelector('form input').getBoundingClientRect(); return { x: r.x + 20, y: r.y + r.height / 2 } })
    await send('Input.dispatchMouseEvent', { type: 'mouseMoved', ...field }); await pause(60)
    assert.equal(await evaluate(() => document.documentElement.hasAttribute('data-solar-cursor')), false)
    assert.notEqual(await evaluate(() => getComputedStyle(document.querySelector('form input')).cursor), 'none')
    await evaluate(() => { const r = document.createRange(); r.selectNodeContents(document.querySelector('main p')); getSelection().removeAllRanges(); getSelection().addRange(r) })
    await pause(60); assert.equal(await evaluate(() => document.documentElement.hasAttribute('data-solar-cursor')), false)
    await evaluate(() => getSelection().removeAllRanges())
    await media('reduce'); await send('Input.dispatchMouseEvent', { type: 'mouseMoved', ...field }); await pause(60)
    assert.equal(await evaluate(() => document.documentElement.hasAttribute('data-solar-cursor')), false)
    await viewport(390); await send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 1 }); await media('no-preference')
    await send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 15, y: 150 }] })
    await send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] }); await pause(60)
    assert.equal(await evaluate(() => document.documentElement.hasAttribute('data-solar-cursor')), false)
    assert.equal(await evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await send('Emulation.setTouchEmulationEnabled', { enabled: false })
  })
  await viewport(1440); await media('no-preference')
  await check('Initial loader only appears for genuine pending initial lazy loading and exits promptly', async () => {
    takePausedRequests()
    await send('Fetch.enable', { patterns: [{ urlPattern: origin + '/src/pages/HomePage.tsx*', requestStage: 'Request' }] })
    await send('Page.navigate', { url: origin + '/' })
    await until(() => !!document.querySelector('[data-initial-loader]'))
    await until(() => document.querySelector('[data-initial-loader] img')?.complete)
    const loader = await evaluate(() => { const el = document.querySelector('[data-initial-loader]'), r = el.getBoundingClientRect(); return { text: el.textContent, top: r.top, height: r.height, color: getComputedStyle(el).backgroundColor } })
    assert.equal(loader.top, 0); assert.equal(loader.height, 900); assert.equal(loader.color, 'rgb(9, 29, 24)')
    assert.ok(loader.text.includes('Rooted in Nature. Powered by the Sun.'))
    await pause(250); await screenshot('initial-solar-loader-1440')
    await until(() => [...document.querySelectorAll('[data-loader-module]')].length === 6 && [...document.querySelectorAll('[data-loader-module]')].every(el => +getComputedStyle(el).opacity > 0.95))
    await until(() => [...document.querySelectorAll('[data-loader-photon]')].some(el => +getComputedStyle(el).opacity > 0.5))
    await screenshot('nature-solar-light-flow-1440')
    await until(() => +getComputedStyle(document.querySelector('[data-loader-brand]')).opacity > 0.95 && +getComputedStyle(document.querySelector('[data-loader-art]')).opacity < 0.05)
    await screenshot('nature-solar-logo-transition-1440')
    const held = takePausedRequests(); assert.ok(held.length > 0)
    const released = Date.now()
    for (const request of held) await send('Fetch.continueRequest', { requestId: request.requestId })
    await send('Fetch.disable')
    await until(() => !!document.querySelector('main h1') && !document.querySelector('[data-initial-loader]'))
    assert.ok(Date.now() - released < 2000, 'Loader must not impose a minimum multi-second delay')
    await evaluate(() => { window.__routeLoaderFlashed = false; new MutationObserver(() => { if (document.querySelector('[data-initial-loader]')) window.__routeLoaderFlashed = true }).observe(document.body, { childList: true, subtree: true }) })
    await evaluate(() => document.querySelector('footer a[href="/terms"]').click())
    await until(() => location.pathname === '/terms' && !!document.querySelector('main h1')); await pause(250)
    assert.equal(await evaluate(() => window.__routeLoaderFlashed), false)
  })
  await viewport(390); await media('reduce')
  await check('Initial loading artwork stays visible and static with reduced motion on mobile', async () => {
    takePausedRequests()
    await send('Fetch.enable', { patterns: [{ urlPattern: origin + '/src/pages/HomePage.tsx*', requestStage: 'Request' }] })
    await send('Page.navigate', { url: origin + '/' })
    await until(() => !!document.querySelector('[data-initial-loader]'))
    await pause(250)
    const before = await evaluate(() => [...document.querySelectorAll('[data-initial-loader] svg, [data-initial-loader] span')].map(el => getComputedStyle(el).transform))
    await pause(250)
    assert.deepEqual(await evaluate(() => [...document.querySelectorAll('[data-initial-loader] svg, [data-initial-loader] span')].map(el => getComputedStyle(el).transform)), before)
    assert.equal(await evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await screenshot('initial-solar-loader-390')
    for (const request of takePausedRequests()) await send('Fetch.continueRequest', { requestId: request.requestId })
    await send('Fetch.disable')
    await until(() => !!document.querySelector('main h1') && !document.querySelector('[data-initial-loader]'))
  })
}
